#!/usr/bin/env python3
"""Generate (or verify) the SCos signed-boot RSA-2048 trust anchor.

The UEFI stub carries only the public modulus.  The private exponent lives in
keys/boot-signing.json and is used by tools/scos_sign.py when the image is
packed.  This is pure Python - no OpenSSL needed on the build machine.

    python3 tools/scos_keys.py --generate       rotate the key pair
    python3 tools/scos_keys.py --verify         header and key must agree

SECURITY NOTE: the key checked into this repository is a *development trust
anchor*.  Its private half is public, so the signature on the shipped image
proves integrity, not publisher identity.  For a real deployment, run
--generate, keep keys/boot-signing.json OFF the repository (add it to your
private release process), and enroll the resulting BOOTX64.EFI in firmware
Secure Boot.  Rotating the key invalidates every previously signed image.
"""
import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / 'boot' / 'uefi' / 'trust_anchor.h'
PRIVATE = ROOT / 'keys' / 'boot-signing.json'
E = 65537


def probable_prime(bits, rng_bytes):
    while True:
        raw = bytearray(rng_bytes(bits // 8))
        raw[0] |= 0x80
        raw[-1] |= 1
        n = int.from_bytes(raw, 'big')
        if n % 3 == 0 or n % 5 == 0 or n % 7 == 0:
            continue
        if miller_rabin(n, 40, rng_bytes):
            return n


def miller_rabin(n, rounds, rng_bytes):
    if n < 2 or n % 2 == 0:
        return False
    d, s = n - 1, 0
    while d % 2 == 0:
        d //= 2
        s += 1
    for _ in range(rounds):
        a = 2 + int.from_bytes(rng_bytes((n.bit_length() + 7) // 8), 'big') % (n - 3)
        x = pow(a, d, n)
        if x == 1 or x == n - 1:
            continue
        for _ in range(s - 1):
            x = x * x % n
            if x == n - 1:
                break
        else:
            return False
    return True


def generate():
    import secrets
    rnd = secrets.token_bytes
    while True:
        p = probable_prime(1024, rnd)
        q = probable_prime(1024, rnd)
        if p == q:
            continue
        n = p * q
        if n.bit_length() != 2048:
            continue
        phi = (p - 1) * (q - 1)
        if phi % E == 0:
            continue
        d = pow(E, -1, phi)
        break
    key = {
        'comment': 'DEVELOPMENT trust anchor. Rotate and protect this file before deployment.',
        'algorithm': 'RSA-2048 PKCS#1 v1.5 / SHA-256',
        'n': format(n, 'x'), 'e': E, 'd': format(d, 'x'),
        'p': format(p, 'x'), 'q': format(q, 'x'),
    }
    PRIVATE.parent.mkdir(parents=True, exist_ok=True)
    PRIVATE.write_text(json.dumps(key, sort_keys=True, indent=2) + '\n')
    write_header(n)
    print('generated RSA-2048 trust anchor; public SHA-256 %s' %
          hashlib.sha256(n.to_bytes(256, 'big')).hexdigest()[:16])
    return 0


def modulus_of_header():
    text = HEADER.read_text()
    values = [int(v, 16) for v in text.split('{', 1)[1].split('}', 1)[0].replace('\n', '').split(',') if v.strip()]
    if len(values) != 256:
        raise ValueError('trust_anchor.h does not hold 256 modulus bytes')
    return bytes(values)


def write_header(n):
    raw = n.to_bytes(256, 'big')
    lines = ['/* Generated by tools/scos_keys.py.  NOT edited by hand.',
             ' * The UEFI stub is the root of trust for every signed boot file.',
             ' * Rotate with `python3 tools/scos_keys.py --generate` and re-sign.',
             ' */', '#ifndef SCOS_TRUST_ANCHOR_H', '#define SCOS_TRUST_ANCHOR_H', '',
             '#include <stdint.h>', '',
             'static const uint8_t boot_trust_modulus[256] = {']
    for i in range(0, 256, 12):
        lines.append('    ' + ', '.join('0x%02x' % b for b in raw[i:i + 12]) + ',')
    lines += ['};', '#define BOOT_TRUST_EXPONENT 65537u', '', '#endif', '']
    HEADER.write_text('\n'.join(lines))


def verify():
    key = json.loads(PRIVATE.read_text())
    n = int(key['n'], 16)
    if key['e'] != E or n.bit_length() != 2048:
        raise SystemExit('FAIL: private key is not a 2048-bit RSA key with e=65537')
    d = int(key['d'], 16)
    probe = 0x53536f73
    if pow(probe, E * d, n) != pow(probe, 1, n):
        raise SystemExit('FAIL: private exponent does not invert e')
    if modulus_of_header() != n.to_bytes(256, 'big'):
        raise SystemExit('FAIL: boot/uefi/trust_anchor.h does not match keys/boot-signing.json')
    print('PASS: the UEFI trust anchor matches the signing key (fingerprint %s)' %
          hashlib.sha256(n.to_bytes(256, 'big')).hexdigest()[:16])
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = ap.add_mutually_exclusive_group(required=True)
    group.add_argument('--generate', action='store_true')
    group.add_argument('--verify', action='store_true')
    args = ap.parse_args()
    return generate() if args.generate else verify()


if __name__ == '__main__':
    sys.exit(main())
