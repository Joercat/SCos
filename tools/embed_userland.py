#!/usr/bin/env python3
"""Embed the CPL3 app-server image into the kernel.

The image is a flat, absolute-linked binary (see kernel/user/user.ld).  It is
mapped into each user-mode process's own PML4 at USER_BASE; no ELF parsing or
runtime relocation happens in the kernel.  Keeping it in the kernel image
means a user-mode app cannot be replaced by writing the ESP: the code that
enforces the boundary is the same code that was stamped into the delivery.
"""
import subprocess
import sys
from pathlib import Path

MAX_IMAGE = 1536 * 1024


def main(src: Path, dst: Path) -> int:
    data = src.read_bytes()
    if not data or len(data) > MAX_IMAGE:
        raise SystemExit(f"userland image is {len(data)} bytes; expected 1..{MAX_IMAGE}")
    if data[:2] != b"\xfc\x48" and data[0] not in (0xFC, 0xFA, 0x55, 0x48):
        raise SystemExit("userland image does not start with plausible entry code")
    elf = src.with_suffix(".elf")
    syms = {}
    if elf.exists():
        text = subprocess.run(["nm", "-n", str(elf)], capture_output=True, text=True,
                              check=True).stdout
        for line in text.splitlines():
            parts = line.split()
            if len(parts) == 3:
                syms[parts[2]] = int(parts[0], 16)
    base = syms.get("user_start", 0)
    total = syms.get("_user_bss_end", base + len(data)) - base
    text_bytes = syms.get("_user_text_end", base + len(data)) - base
    out = [
        "/* Generated by tools/embed_userland.py - do not edit. */\n",
        "#ifndef SCOS_USERLAND_IMAGE_H\n#define SCOS_USERLAND_IMAGE_H\n",
        f"#define USERLAND_IMAGE_BYTES {len(data)}\n",
        f"#define USERLAND_TOTAL_BYTES {total}\n",
        f"#define USERLAND_TEXT_BYTES {text_bytes}\n",
        "static const unsigned char userland_image[USERLAND_IMAGE_BYTES] = {\n",
    ]
    for i in range(0, len(data), 16):
        out.append("    " + ",".join(str(b) for b in data[i:i + 16]) + ",\n")
    out.append("};\n#endif\n")
    dst.write_text("".join(out))
    print(f"embedded CPL3 app server: {len(data)} bytes")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit("usage: embed_userland.py <userland.bin> <output.h>")
    sys.exit(main(Path(sys.argv[1]), Path(sys.argv[2])))
